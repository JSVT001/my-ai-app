export default async function handler(req, res) {
  res.setHeader('Content-Type', 'application/json');

  if (req.method !== 'POST') {
    return res.status(405).json({ reply: 'Method not allowed' });
  }

  const { prompt } = req.body;
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    return res.status(500).json({ reply: "API Key is missing in Vercel settings." });
  }

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }]
        })
      }
    );

    const data = await response.json();

    if (!response.ok) {
      return res.status(500).json({ 
        reply: `API Error: ${data.error?.message || "Unknown API error"}` 
      });
    }

    const candidate = data.candidates?.[0];
    const reply = candidate?.content?.parts?.[0]?.text;

    if (!reply) {
      return res.status(200).json({ reply: "No text generated by the model." });
    }

    return res.status(200).json({ reply });
  } catch (error) {
    return res.status(500).json({ reply: `Server Error: ${error.message}` });
  }
}
